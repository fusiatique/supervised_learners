"""Grid environments. States are numbered s1, s2, ... row by row from the top
left, so a 3x3 grid has s5 in the centre."""

import random

from manim import DOWN, LEFT, ORIGIN, RIGHT, UP, Line, MathTex, Square, VGroup

from .theme import CELL, INK, MUTED, WALL

ACTIONS = {"up": UP, "down": DOWN, "left": LEFT, "right": RIGHT}
_DELTAS = {"up": (-1, 0), "down": (1, 0), "left": (0, -1), "right": (0, 1)}


def _cell_center(r, c, rows, cols, cell):
    return ORIGIN + (c - (cols - 1) / 2) * cell * RIGHT + (r - (rows - 1) / 2) * cell * DOWN


class GridWorld(VGroup):
    def __init__(self, rows=3, cols=3, cell=1.8, walls=(), **kwargs):
        super().__init__(**kwargs)
        self.rows, self.cols, self.cell = rows, cols, cell
        self.walls = set(walls)
        self.cells = VGroup()
        for s in range(1, rows * cols + 1):
            fill = WALL if s in self.walls else CELL
            square = Square(side_length=cell, stroke_color=INK, stroke_width=2, fill_color=fill, fill_opacity=1)
            square.move_to(_cell_center(*divmod(s - 1, cols), rows, cols, cell))
            self.cells.add(square)
        self.add(self.cells)

    def __getitem__(self, s):
        """The cell for state s (1-based)."""
        return self.cells[s - 1]

    def center_of(self, s):
        return self[s].get_center()

    def make_labels(self, opacity=0.2):
        """Large, faint s_i watermarks centred in each open cell, layered above the cells
        (so highlighting a cell never hides its label) and below arrows and the agent."""
        labels = VGroup()
        for s in range(1, self.rows * self.cols + 1):
            if s in self.walls:
                continue
            label = MathTex(f"s_{{{s}}}", color=INK).set_opacity(opacity)
            label.scale_to_fit_height(0.42 * self.cell).move_to(self[s])
            labels.add(label)
        return labels.set_z_index(1)

    def step(self, s, action):
        """The transition function f(s, a): the next state, staying put at edges and walls."""
        r, c = divmod(s - 1, self.cols)
        dr, dc = _DELTAS[action]
        r2, c2 = r + dr, c + dc
        if not (0 <= r2 < self.rows and 0 <= c2 < self.cols):
            return s
        s2 = r2 * self.cols + c2 + 1
        return s if s2 in self.walls else s2


class Maze(VGroup):
    """A perfect maze drawn as walls on cell edges, with faint grid lines marking
    the cells. Generated by a seeded depth-first search, so it is the same every render."""

    def __init__(self, rows=7, cols=7, cell=0.9, seed=4, **kwargs):
        super().__init__(**kwargs)
        self.rows, self.cols, self.cell = rows, cols, cell
        open_edges = self._carve(rows, cols, random.Random(seed))
        width, height = cols * cell, rows * cell

        self.outline = Square(side_length=1).stretch_to_fit_width(width).stretch_to_fit_height(height)
        self.outline.set_stroke(INK, width=6).set_fill(CELL, opacity=1)

        self.walls = VGroup()
        for r in range(rows):
            for c in range(cols):
                center = _cell_center(r, c, rows, cols, cell)
                if c + 1 < cols and ((r, c), (r, c + 1)) not in open_edges:
                    self.walls.add(Line(center + cell / 2 * (RIGHT + UP), center + cell / 2 * (RIGHT + DOWN)))
                if r + 1 < rows and ((r, c), (r + 1, c)) not in open_edges:
                    self.walls.add(Line(center + cell / 2 * (DOWN + LEFT), center + cell / 2 * (DOWN + RIGHT)))
        self.walls.set_stroke(INK, width=6)

        self.gridlines = VGroup(
            *[Line(UP * height / 2, DOWN * height / 2).shift((c - cols / 2) * cell * RIGHT) for c in range(1, cols)],
            *[Line(LEFT * width / 2, RIGHT * width / 2).shift((r - rows / 2) * cell * DOWN) for r in range(1, rows)],
        ).set_stroke(MUTED, width=1.5, opacity=0.3)

        self.add(self.outline, self.gridlines, self.walls)

    def center_of(self, s):
        return _cell_center(*divmod(s - 1, self.cols), self.rows, self.cols, self.cell)

    @staticmethod
    def _carve(rows, cols, rng):
        """Depth-first search from the top-left cell; returns the set of opened edges."""
        seen, stack, opened = {(0, 0)}, [(0, 0)], set()
        while stack:
            r, c = stack[-1]
            nbrs = [(r + dr, c + dc) for dr, dc in _DELTAS.values()
                    if 0 <= r + dr < rows and 0 <= c + dc < cols and (r + dr, c + dc) not in seen]
            if not nbrs:
                stack.pop()
                continue
            nxt = rng.choice(nbrs)
            opened.add(tuple(sorted([(r, c), nxt])))
            seen.add(nxt)
            stack.append(nxt)
        return opened

import assert from 'node:assert/strict';
import React from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
import {SCENE03_5,T035,getDopamineIntroductionState,CocaineReinforcementExample,DopamineBeyondPleasure,RewardPredictionErrorIntroduction} from '../src/Scene03_5_DopamineIntroduction';
import {DopamineCircuitBridge} from '../src/dopamine-introduction-components';
import {getScene04State} from '../src/Scene04_MesocorticolimbicIntroduction';
assert.deepEqual(SCENE03_5,{width:1920,height:1080,fps:30,durationInFrames:2100});
assert.equal(T035.beyondPleasure,33*30);
assert.equal(T035.prediction,59*30);
for(let f=0;f<990;f++)assert.equal(getDopamineIntroductionState(f).pleasureVisible,false);
for(let f=0;f<1770;f++)assert.equal(getDopamineIntroductionState(f).predictionVisible,false);
assert.equal(getDopamineIntroductionState(990).citation,'Volkow et al., 2011');
assert.equal(getDopamineIntroductionState(1410).citation,'Bromberg-Martin et al., 2010');
assert.equal(getDopamineIntroductionState(1770).citation,null);
const render=(element:React.ReactNode)=>renderToStaticMarkup(<svg>{element}</svg>);
for(const f of [810,900,989])assert.ok(!render(<CocaineReinforcementExample f={f}/>).includes('PLEASURE'));
assert.ok(render(<DopamineBeyondPleasure f={1020}/>).includes('THE PLEASURE MOLECULE?'));
const end=render(<RewardPredictionErrorIntroduction f={2099}/>);
assert.ok(end.includes('opacity="0"'),'The explanatory overlay has faded before the brain handoff');
for(const f of [0,30,100])assert.equal(render(<DopamineCircuitBridge frame={f}/>),render(<DopamineCircuitBridge frame={f}/>));
assert.equal(getScene04State(0).brainAmount,.35,'Scene 04 continues the partial brain');
const forward=Array.from({length:2100},(_,f)=>JSON.stringify(getDopamineIntroductionState(f)));
for(let f=2099;f>=0;f--)assert.equal(JSON.stringify(getDopamineIntroductionState(f)),forward[f]);
console.log('PASS: 70 seconds, 1080p30; 33-second and 59-second boundaries; citations; deterministic reverse scrubbing; partial-brain continuity.');
